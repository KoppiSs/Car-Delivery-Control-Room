// Pure helpers for showing names instead of record ids. Safe to use in the browser.

export const ID_PATTERN = /\b(?:drv|cus|site|veh|ord)-[0-9a-z]+\b/gi

/** Replace known ids in a text with their names; unknown ids stay as they are. */
export function withNames(text: string, names: Record<string, string>): string {
  return text.replace(ID_PATTERN, (id) => names[id] ?? id)
}

/** The ids a text mentions, for a details toggle. */
export function idsIn(text: string): string[] {
  return [...new Set(text.match(ID_PATTERN) ?? [])]
}

export type FollowUpRecipient = "customer" | "pickup_site" | "delivery_site" | "driver" | "nobody"

// "Customer (dealer)": the dealer who bought the car, not the seller at the pickup site.
export const FOLLOW_UP_RECIPIENT_LABELS: Record<FollowUpRecipient, string> = {
  customer: "Customer (dealer)", pickup_site: "Pickup site (seller)", delivery_site: "Delivery site", driver: "Driver", nobody: "Nobody, no question to ask",
}

/** Who the plan's text names, in the order the words appear. Searched with the word boundaries below. */
const NAMED_RECIPIENTS: [Exclude<FollowUpRecipient, "nobody">, RegExp][] = [
  ["customer", /\b(?:customer|dealer|buyer)\b/i],
  ["pickup_site", /\b(?:pickup site|pickup location|collection site|seller)\b/i],
  ["delivery_site", /\b(?:delivery site|receiving site|delivery location)\b/i],
  ["driver", /\bdriver\b/i],
]

/**
 * The recipient a plan names ("Request customer confirmation…" → customer): whoever is named first in
 * the action, else in what we wait for. Null when the plan names no one; a person always confirms it.
 */
export function suggestedRecipient(action: string, waitingOn = ""): FollowUpRecipient | null {
  for (const text of [action, waitingOn]) {
    const found = NAMED_RECIPIENTS.map(([recipient, pattern]) => ({ recipient, at: text.search(pattern) }))
      .filter((entry) => entry.at >= 0).sort((a, b) => a.at - b.at)[0]
    if (found) return found.recipient
  }
  return null
}


/** "Agent's verdict: fine" — the agent's verdict as a word, never its own sentence. */
export function verdictText(value: unknown): string | null {
  return value === "fine" ? "Agent's verdict: fine" : value === "needs_person" ? "Agent's verdict: needs a person"
    : value === "unsure" ? "Agent's verdict: unsure" : null
}

/** Where a simulated reply came from. Stored on the message, so the label survives a refresh. */
export type ReplySource = "scripted" | "model" | "fallback" | "operator"

export const REPLY_SOURCE_LABELS: Record<ReplySource, string> = {
  scripted: "Scripted reply (simulation)",
  model: "Generated by the local model (simulation)",
  fallback: "Fallback reply (simulation)",
  operator: "Written by the operator (simulation)",
}

export function replySourceLabel(value: unknown): string | null {
  return typeof value === "string" && value in REPLY_SOURCE_LABELS ? REPLY_SOURCE_LABELS[value as ReplySource] : null
}
