import { expect, test } from "./messages-fixtures"

test("message rows expand locally, show chronological history and offer deliberate order navigation", async ({ page, request, messageOrders }) => {
  await page.goto("/inbox?view=all")
  const rows = page.locator(".message-thread-list > li")
  await expect(rows.first()).toBeVisible()
  expect(await rows.count()).toBeGreaterThan(1)
  const first = rows.filter({ has: page.locator(`[aria-controls="message-history-${messageOrders.first}"]`) })
  const second = rows.filter({ has: page.locator(`[aria-controls="message-history-${messageOrders.second}"]`) })
  const orderId = await first.getAttribute("data-order-id")
  expect(orderId).toBeTruthy()
  const firstButton = first.locator("button.message-thread")
  const secondButton = second.locator("button.message-thread")
  await expect(firstButton).toHaveAttribute("aria-expanded", "false")
  await expect(page.getByRole("link", { name: "View Order", exact: true })).toHaveCount(0)

  const detailResponse = await request.get(`/api/orders/${orderId}`)
  expect(detailResponse.ok()).toBeTruthy()
  const detail = await detailResponse.json()
  const expectedMessages = detail.messages.filter((message: { orderId: string }) => message.orderId === orderId)
    .sort((a: { authoredAt: string; id: string }, b: { authoredAt: string; id: string }) => a.authoredAt.localeCompare(b.authoredAt) || a.id.localeCompare(b.id))
  const inboxUrl = page.url()
  await firstButton.click()
  await expect(firstButton).toHaveAttribute("aria-expanded", "true")
  expect(page.url()).toBe(inboxUrl)
  const history = first.locator(".message-thread-expanded")
  await expect(history).toBeVisible()
  const renderedIds = await history.locator("[data-message-id]").evaluateAll((elements) => elements.map((element) => element.getAttribute("data-message-id")))
  expect(renderedIds).toEqual(expectedMessages.map((message: { id: string }) => message.id))
  for (const message of expectedMessages) {
    await expect(history.locator(`[data-message-id="${message.id}"] .msg-body`)).toHaveText(message.body)
  }
  await expect(history.getByRole("link", { name: "View Order", exact: true })).toHaveAttribute("href", `/cases/${orderId}`)

  await secondButton.click()
  await expect(firstButton).toHaveAttribute("aria-expanded", "false")
  await expect(first.locator(".message-thread-expanded")).toHaveCount(0)
  await expect(secondButton).toHaveAttribute("aria-expanded", "true")
  await expect(page.locator(".message-thread-expanded")).toHaveCount(1)
  expect(page.url()).toBe(inboxUrl)
  await secondButton.click()
  await expect(page.locator(".message-thread-expanded")).toHaveCount(0)

  await firstButton.focus()
  await page.keyboard.press("Enter")
  await expect(firstButton).toHaveAttribute("aria-expanded", "true")
  await first.getByRole("link", { name: "View Order", exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/orders/${orderId}$`))
  await expect(page.locator("main")).toContainText(detail.order.reference)
})
